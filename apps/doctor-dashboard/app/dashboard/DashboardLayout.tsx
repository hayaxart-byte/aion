export function DashboardLayout({ children }: { children: ReactNode }) {
  const { user, loading, client, logout } = useAuth();
  const router = useRouter();
  const [ready, setReady] = useState(false);
  const redirected = useRef(false);

  useEffect(() => {
    if (loading) return;

    if (!user) {
      if (redirected.current) return;
      const profile = client.getProfile();
      if (profile) {
        setReady(true);
        return;
      }
      redirected.current = true;
      router.replace('/login');
      return;
    }

    const allowedRoles = ['doctor', 'receptionist', 'nurse'];
    if (!user.roles.some(r => allowedRoles.includes(r))) {
      redirected.current = true;
      router.replace('/forbidden');
      return;
    }

    setReady(true);
  }, [user, loading, client, router]);

  if (!ready) {
    return (
      <div className="min-h-screen flex items-center justify-center">
        <Spinner />
      </div>
    );
  }

  return (
    <AppShell
      navItems={navItems}
      title="Aion"
      userName={user?.name}
      userRole={user ? getPrimaryRoleLabel(user.roles as any) : undefined}
      onLogout={logout}
    >
      {children}
    </AppShell>
  );
}
